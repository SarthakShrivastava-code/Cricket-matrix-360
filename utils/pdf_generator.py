import io

from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas


def generate_player_pdf(player_name, stats_dict):
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=letter)

    pdf.setFont("Helvetica-Bold", 20)
    pdf.setFillColorRGB(0.1, 0.21, 0.36)
    pdf.drawString(50, 750, f"Scouting Report: {player_name}")

    pdf.setFont("Helvetica", 12)
    pdf.setFillColorRGB(0.3, 0.3, 0.3)
    pdf.drawString(50, 730, "Generated by CricketMatrix360 Intelligence Engine")
    pdf.line(50, 720, 560, 720)

    y = 680
    for metric, value in stats_dict.items():
        pdf.setFont("Helvetica-Bold", 12)
        pdf.drawString(50, y, f"{metric}:")
        pdf.setFont("Helvetica", 12)
        pdf.drawString(200, y, str(value))
        y -= 25

    pdf.showPage()
    pdf.save()
    buffer.seek(0)
    return buffer